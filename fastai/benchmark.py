"""Learner.benchmark() -- profile inference latency, throughput, and memory across batch sizes.

Patches a ``benchmark`` method onto :class:`~fastai.learner.Learner` via
:func:`fastcore.basics.patch` so that no autogenerated files need editing.

Usage::

    from fastai.benchmark import *          # patches Learner.benchmark
    learn = synth_learner()
    results = learn.benchmark()             # uses sensible defaults
    results = learn.benchmark(batch_sizes=(1, 4), n_batches=20)

Each element of the returned list is a :class:`BenchmarkResult` dataclass
carrying ``batch_size``, ``n_batches``, ``total_samples``, ``avg_latency_ms``,
``std_latency_ms``, ``throughput_samples_per_sec``, and ``peak_memory_bytes``.
"""

import time
import tracemalloc
from dataclasses import dataclass
from typing import List, Sequence, Tuple

import torch

__all__ = ['BenchmarkResult', 'benchmark']

# ---------------------------------------------------------------------------
# Graceful imports -- mirror the pattern in fastai/callback/gradient_noise.py
# so the module stays functional even when the full fastai stack is absent.
# ---------------------------------------------------------------------------
try:
    from fastai.learner import Learner as _Learner
    from fastcore.basics import patch as _patch
except Exception:
    # Provide minimal stubs so the module can still be imported in isolation
    # (e.g., for unit-testing the pure-logic helpers).
    class _Learner:
        dls = None
        model = None
        training = False
        logger = print
    _patch = None

# ---------------------------------------------------------------------------
# Result container
# ---------------------------------------------------------------------------

@dataclass
class BenchmarkResult:
    """Holds profiling results for a single batch-size run."""
    batch_size: int
    n_batches: int
    total_samples: int
    avg_latency_ms: float
    std_latency_ms: float
    throughput_samples_per_sec: float
    peak_memory_bytes: int


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

def _infer_input_shape(dl) -> Tuple[int, ...]:
    """Return the shape of a single input sample (excluding batch dim) from *dl*.

    Falls back to ``(1,)`` when the dataloader is empty or its contents are
    not standard tensors.
    """
    try:
        batch = next(iter(dl))
        # fastai DataLoaders yield (xb, yb) tuples; xb may itself be a tuple
        xb = batch[0]
        if isinstance(xb, (list, tuple)):
            xb = xb[0]
        return tuple(xb.shape[1:])  # drop batch dim
    except (StopIteration, IndexError, AttributeError):
        return (1,)


def _synthetic_batch(shape: Tuple[int, ...], batch_size: int,
                     device: torch.device, dtype: torch.dtype) -> torch.Tensor:
    """Create a random tensor of ``(batch_size, *shape)`` on *device*."""
    return torch.randn(batch_size, *shape, device=device, dtype=dtype)


def _time_batches(model, batches: List[torch.Tensor]) -> List[float]:
    """Run forward passes and return per-batch wall-clock durations in seconds."""
    latencies: List[float] = []
    for xb in batches:
        start = time.perf_counter()
        model(xb)
        latencies.append(time.perf_counter() - start)
    return latencies


def _format_table(results: List[BenchmarkResult]) -> str:
    """Return a human-readable table summarising *results*."""
    header = (
        f"{'Batch':>7s}  {'Batches':>7s}  {'Samples':>8s}  "
        f"{'Avg(ms)':>9s}  {'Std(ms)':>9s}  "
        f"{'Throughput':>12s}  {'PeakMem(B)':>12s}"
    )
    sep = "-" * len(header)
    lines = [sep, header, sep]
    for r in results:
        lines.append(
            f"{r.batch_size:>7d}  {r.n_batches:>7d}  {r.total_samples:>8d}  "
            f"{r.avg_latency_ms:>9.2f}  {r.std_latency_ms:>9.2f}  "
            f"{r.throughput_samples_per_sec:>12.1f}  {r.peak_memory_bytes:>12d}"
        )
    lines.append(sep)
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# The benchmark method itself
# ---------------------------------------------------------------------------

def _benchmark_impl(
    learner,
    batch_sizes: Sequence[int] = (1, 8, 16, 32, 64),
    n_batches: int = 10,
    warmup_batches: int = 3,
    device=None,
) -> List[BenchmarkResult]:
    """Profile inference latency, throughput, and memory for each batch size.

    Parameters
    ----------
    batch_sizes : sequence of int
        Batch sizes to benchmark.
    n_batches : int
        Number of timed forward-pass batches per batch size.
    warmup_batches : int
        Untimed warmup batches run before timing starts.
    device : torch.device | str | None
        Override device.  ``None`` keeps the model's current device.

    Returns
    -------
    list[BenchmarkResult]
        One entry per batch size with latency, throughput, and memory stats.
    """
    model = learner.model
    was_training = model.training

    # Determine device
    if device is not None:
        dev = torch.device(device)
    else:
        try:
            dev = next(model.parameters()).device
        except StopIteration:
            dev = torch.device("cpu")

    # Determine input shape from the validation DataLoader
    dl = learner.dls.valid if learner.dls is not None else None
    input_shape = _infer_input_shape(dl) if dl is not None else (1,)

    # Determine dtype from model parameters
    try:
        dtype = next(model.parameters()).dtype
    except StopIteration:
        dtype = torch.float32

    use_cuda = dev.type == "cuda" and torch.cuda.is_available()

    results: List[BenchmarkResult] = []

    model.eval()
    try:
        with torch.no_grad():
            for bs in batch_sizes:
                # --- prepare synthetic data ---------------------------------
                all_batches = [
                    _synthetic_batch(input_shape, bs, dev, dtype)
                    for _ in range(warmup_batches + n_batches)
                ]
                warmup = all_batches[:warmup_batches]
                timed = all_batches[warmup_batches:]

                # --- warmup -------------------------------------------------
                for xb in warmup:
                    model(xb)

                # --- measure memory + latency -------------------------------
                if use_cuda:
                    torch.cuda.reset_peak_memory_stats(dev)
                    torch.cuda.synchronize(dev)
                    latencies = _time_batches(model, timed)
                    torch.cuda.synchronize(dev)
                    peak_mem = torch.cuda.max_memory_allocated(dev)
                else:
                    tracemalloc.start()
                    latencies = _time_batches(model, timed)
                    _, peak_mem = tracemalloc.get_traced_memory()
                    tracemalloc.stop()

                # --- aggregate ----------------------------------------------
                total_samples = bs * n_batches
                mean_s = sum(latencies) / len(latencies)
                var_s = (
                    sum((l - mean_s) ** 2 for l in latencies) / len(latencies)
                )
                std_s = var_s ** 0.5
                throughput = total_samples / sum(latencies) if sum(latencies) > 0 else 0.0

                results.append(BenchmarkResult(
                    batch_size=bs,
                    n_batches=n_batches,
                    total_samples=total_samples,
                    avg_latency_ms=mean_s * 1000.0,
                    std_latency_ms=std_s * 1000.0,
                    throughput_samples_per_sec=throughput,
                    peak_memory_bytes=peak_mem,
                ))
    finally:
        # Restore original training state
        model.train(was_training)

    # Print summary via the learner's logger (defaults to ``print``)
    learner.logger(_format_table(results))

    return results


# ---------------------------------------------------------------------------
# Patch onto Learner when fastcore is available
# ---------------------------------------------------------------------------
if _patch is not None:
    @_patch
    def benchmark(
        self: _Learner,
        batch_sizes: Sequence[int] = (1, 8, 16, 32, 64),
        n_batches: int = 10,
        warmup_batches: int = 3,
        device=None,
    ) -> List[BenchmarkResult]:
        """Profile inference latency, throughput, and memory across batch sizes.

        See :func:`_benchmark_impl` for full parameter documentation.
        """
        return _benchmark_impl(self, batch_sizes, n_batches, warmup_batches, device)
